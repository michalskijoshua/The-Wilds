"""Spawn eggs, one per look (24 Nov 2026, lowest-priority item of the build handoff).
Each egg icon is Minecraft's own egg template, coloured from that look's texture: its most common colour for the shell,
the most different of its next colours for the spots (no Codex sprites). Writes the egg items, their icons, names and
the list the script reads (scripts/eggs_data.js). Usage: python3 tools/egg_build.py  (needs /tmp/bsamp, Mojang's samples)
"""
import json, os
from PIL import Image
ROOT = os.path.join(os.path.dirname(__file__), "..")
RP, BP = os.path.join(ROOT, "TheWilds_RP"), os.path.join(ROOT, "TheWilds_BP")
TPL = "/tmp/bsamp/resource_pack/textures/items/"
EGGS = []   # (creature, look, label, texture)
for k, n in (("savanna", "Savanna"), ("badlands", "Badlands"), ("tundra", "Tundra")):
    EGGS.append(("tuskbeast", k, f"{n} Tuskbeast", f"textures/entity/tuskbeast/{k}_tuskbeast.png"))
for f, n in (("original", "Aetherseed"), ("bloom", "Bloom Aetherseed"), ("withered", "Withered Aetherseed")):
    EGGS.append(("aetherseed", f, n, f"textures/entity/aetherseed/aetherseed_{f}.png"))
for l, n in (("original", "Bloomling"), ("ember_tulip", "Ember Tulip Bloomling"), ("sunbonnet", "Sunbonnet Bloomling"), ("moonbell", "Moonbell Bloomling"),
             ("froststar", "Froststar Bloomling"), ("poppy_patch", "Poppy Patch Bloomling"), ("clover_puff", "Clover Puff Bloomling"), ("dusk_orchid", "Dusk Orchid Bloomling")):
    EGGS.append(("bloomling", l, n, f"textures/entity/bloomling/bloomling_{l}.png"))
for f in ("stone", "mossy", "sand", "clay", "coal", "copper", "iron", "gold", "diamond", "netherite"):
    EGGS.append(("pebble_mimic", f, f"{f.title()} Pebble Mimic", f"textures/entity/pebble_mimic/pebble_mimic_{f}.png"))

def palette(path):
    im = Image.open(os.path.join(RP, path)).convert("RGBA")
    px = [p[:3] for p in im.getdata() if p[3] > 200]
    q = Image.new("RGB", (len(px), 1)); q.putdata(px)
    pal = q.quantize(colors=8, method=Image.Quantize.MEDIANCUT)
    counts = sorted(pal.getcolors(), reverse=True); cols = pal.getpalette()
    rgb = [tuple(cols[i * 3:i * 3 + 3]) for _, i in counts]
    base = rgb[0]
    sat = lambda c: max(c) - min(c)                        # livelier colours make better spots
    spot = max(rgb[1:7] or [base], key=lambda c: sum((a - b) ** 2 for a, b in zip(c, base)) ** 0.5 + 1.5 * sat(c))
    return base, spot
def tint(img, c):
    img = img.convert("RGBA"); top = max(max(p[:3]) for p in img.getdata() if p[3]) or 255   # template brightest = full colour
    img.putdata([(min(255, r * 255 // top), min(255, g * 255 // top), min(255, b * 255 // top), a) for r, g, b, a in img.getdata()])
    out = Image.new("RGBA", img.size)
    out.putdata([(r * c[0] // 255, g * c[1] // 255, b * c[2] // 255, a) for r, g, b, a in img.getdata()])
    return out
egg, over = Image.open(TPL + "spawn_egg.png"), Image.open(TPL + "spawn_egg_overlay.png")
os.makedirs(os.path.join(RP, "textures/items/wilds_eggs"), exist_ok=True); os.makedirs(os.path.join(BP, "items/eggs"), exist_ok=True)
tex = json.load(open(os.path.join(RP, "textures/item_texture.json")))
lang = [l for l in open(os.path.join(RP, "texts/en_US.lang")).read().splitlines() if not l.startswith("item.wilds:egg_")]
data = []
for creature, look, label, path in EGGS:
    ident = f"wilds:egg_{creature}_{look}"; icon = f"wilds_egg_{creature}_{look}"
    base, spot = palette(path)
    Image.alpha_composite(tint(egg, base), tint(over, spot)).save(os.path.join(RP, f"textures/items/wilds_eggs/{icon}.png"))
    tex["texture_data"][icon] = {"textures": f"textures/items/wilds_eggs/{icon}"}
    item = {"format_version": "1.21.90", "minecraft:item": {"description": {"identifier": ident,
            "menu_category": {"category": "nature", "group": "minecraft:itemGroup.name.mobEgg"}},
            "components": {"minecraft:icon": icon, "minecraft:display_name": {"value": f"item.{ident}.name"}, "minecraft:max_stack_size": 64}}}
    json.dump(item, open(os.path.join(BP, f"items/eggs/egg_{creature}_{look}.json"), "w"), indent=2)
    lang.append(f"item.{ident}.name={label} Spawn Egg")
    data.append({"id": ident, "creature": creature, "look": look})
json.dump(tex, open(os.path.join(RP, "textures/item_texture.json"), "w"), indent=2)
open(os.path.join(RP, "texts/en_US.lang"), "w").write("\n".join(lang) + "\n")
open(os.path.join(BP, "scripts/eggs_data.js"), "w").write("// Generated by tools/egg_build.py\nexport const EGGS = " + json.dumps(data, indent=1) + ";\n")
print(len(EGGS), "eggs")
